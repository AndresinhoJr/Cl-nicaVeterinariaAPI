export function getSpeciesIcon(especie: string, size = 20) {
  const norm = (especie || '').toLowerCase().trim();
  if (norm.includes('perr') || norm.includes('can')) return <DogSpeciesIcon size={size} />;
  if (norm.includes('gat') || norm.includes('felin')) return <CatSpeciesIcon size={size} />;
  if (norm.includes('av') || norm.includes('pajar')) return <BirdSpeciesIcon size={size} />;
  if (norm.includes('conej') || norm.includes('roed')) return <RabbitSpeciesIcon size={size} />;
  if (norm.includes('rept') || norm.includes('iguan') || norm.includes('tortug')) return <ReptileSpeciesIcon size={size} />;
  return <GenericPetIcon size={size} />;
}


